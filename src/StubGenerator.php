<?php

declare(strict_types=1);

namespace yii2\extensions\mago;

use InvalidArgumentException;

/** Generates sparse Mago source patches; the returned PHP must never be loaded at runtime. */
final class StubGenerator
{
    public static function generate(ServiceMap $services): string
    {
        return self::generatePatch($services);
    }

    /**
     * Register patch in source.patches and keys in source.includes, never in runtime autoloading.
     *
     * @return array{patch: string, keys: string}
     */
    public static function generateWithParamsKeys(ServiceMap $services): array
    {
        $keys = array_values(self::collectStringKeys($services->getParams()));
        sort($keys, SORT_STRING);
        // Only key bytes determine identity; configured values may contain objects, resources or closures.
        $class = 'ParamsKeys_' . hash('sha256', serialize($keys));
        $namespace = 'yii2\\extensions\\mago\\generated';
        $helper =
            "<?php\n\ndeclare(strict_types=1);\n\nnamespace "
            . $namespace
            . ";\n\n"
            . "// Generated by mago-yii2-stubs. Analysis only: never require this file at runtime.\n"
            . 'final class '
            . $class
            . "\n{\n";
        foreach ($keys as $index => $key) {
            $helper .= '    public const KEY_' . $index . ' = ' . var_export($key, true) . ";\n";
        }
        $helper .= "}\n";

        return [
            'patch' => self::generatePatch($services, '\\' . $namespace . '\\' . $class, array_flip($keys)),
            'keys' => $helper,
        ];
    }

    /**
     * @param array<array-key, mixed> $params
     * @return array<string, string>
     */
    private static function collectStringKeys(array $params): array
    {
        $keys = [];
        foreach ($params as $key => $value) {
            if (is_string($key)) {
                $keys[$key] = $key;
            }
            if (is_array($value)) {
                $keys += self::collectStringKeys($value);
            }
        }

        return $keys;
    }

    /** @param array<string, int> $keyNames */
    private static function generatePatch(ServiceMap $services, ?string $keysClass = null, array $keyNames = []): string
    {
        $class = ltrim($services->getApplicationType(), '\\');
        if (
            preg_match(
                '/^[a-zA-Z_\x80-\xff][a-zA-Z0-9_\x80-\xff]*(?:\\\\[a-zA-Z_\x80-\xff][a-zA-Z0-9_\x80-\xff]*)*$/D',
                $class,
            ) !== 1
            || in_array(strtolower($class), ['self', 'parent', 'static'], true)
        ) {
            throw new InvalidArgumentException(
                'The configured application type must be a valid fully qualified PHP class name.',
            );
        }

        $patch =
            "<?php\n\ndeclare(strict_types=1);\n\n"
            . "namespace yii;\n\n"
            . "// Generated by mago-yii2-stubs. Analysis only: never require this file at runtime.\n"
            . "class BaseYii\n{\n"
            . "    /** @var \\"
            . $class
            . " */\n"
            . '    public static $app;'
            . "\n}\n";
        $params = self::paramsType($services->getParams(), $keysClass, $keyNames);
        if ($params !== null) {
            $patch .=
                "\nnamespace yii\\base;\n\nclass Module\n{\n    /** @var " . $params . " */\n    public \$params;\n}\n";
        }

        return $patch;
    }

    /**
     * @param array<array-key, mixed> $params
     * @param array<string, int> $keyNames
     */
    private static function paramsType(array $params, ?string $keysClass, array $keyNames): ?string
    {
        if ($params === []) {
            return 'array<array-key, mixed>';
        }
        $items = [];
        foreach ($params as $key => $value) {
            $name = is_int($key)
                ? (string) $key
                : ($keysClass !== null ? $keysClass . '::KEY_' . $keyNames[$key] : self::literalKey($key));
            if ($name === null) {
                return null;
            }
            $type = match (true) {
                is_array($value) => self::paramsType($value, $keysClass, $keyNames),
                is_string($value) => 'string',
                is_int($value) => 'int',
                is_float($value) => 'float',
                is_bool($value) => 'bool',
                $value === null => 'null',
                default => 'mixed',
            };
            if ($type === null) {
                return null;
            }
            $items[] = $name . ': ' . $type;
        }

        return 'array{' . implode(', ', $items) . '}';
    }

    private static function literalKey(string $key): ?string
    {
        // Mago preserves PHPDoc escape bytes literally; use a delimiter absent from the key.
        if (str_contains($key, '*/') || preg_match('/[\x00-\x1f\x7f]/', $key) === 1 || str_ends_with($key, '\\')) {
            return null;
        }
        if (!str_contains($key, "'")) {
            return "'" . $key . "'";
        }
        if (!str_contains($key, '"')) {
            return '"' . $key . '"';
        }

        return null;
    }
}
